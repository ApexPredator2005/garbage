"use client";

import React, { useState, useEffect } from "react";

interface UtrPaymentModalProps {
  isOpen: boolean;
  onClose: () => void;
  invoiceId: string;
  invoiceNumber: string;
  totalDue: number;
  onSuccess: (submissionId: string) => void;
}

export const UtrPaymentModal: React.FC<UtrPaymentModalProps> = ({
  isOpen,
  onClose,
  invoiceId,
  invoiceNumber,
  totalDue,
  onSuccess,
}) => {
  const [utrNumber, setUtrNumber] = useState("");
  const [amountDeclared, setAmountDeclared] = useState(totalDue.toString());
  const [receiptUrl, setReceiptUrl] = useState("");
  const [idempotencyKey, setIdempotencyKey] = useState("");
  const [isSubmitting, setIsSubmitting] = useState(false);
  const [errorMessage, setErrorMessage] = useState("");
  const [successInfo, setSuccessInfo] = useState<string | null>(null);

  // Generate unique UUID idempotency key when the modal opens
  useEffect(() => {
    if (isOpen) {
      const newKey = typeof crypto !== "undefined" && crypto.randomUUID
        ? crypto.randomUUID()
        : `idemp_${Date.now()}_${Math.random().toString(36).substring(2, 9)}`;
      setIdempotencyKey(newKey);
      setErrorMessage("");
      setSuccessInfo(null);
    }
  }, [isOpen]);

  if (!isOpen) return null;

  const handleSubmit = async (e: React.FormEvent) => {
    e.preventDefault();

    if (!utrNumber.trim() || utrNumber.length < 8) {
      setErrorMessage("Please enter a valid Bank UTR (min 8 alphanumeric characters).");
      return;
    }

    const parsedAmount = parseFloat(amountDeclared);
    if (isNaN(parsedAmount) || parsedAmount <= 0) {
      setErrorMessage("Please enter a valid payment amount.");
      return;
    }

    try {
      // 1. Optimistic UI: Disable button immediately to prevent local double-clicks
      setIsSubmitting(true);
      setErrorMessage("");

      // 2. Submit with strict Idempotency-Key
      const response = await fetch("/api/fees/submit-utr", {
        method: "POST",
        headers: {
          "Content-Type": "application/json",
          "Idempotency-Key": idempotencyKey,
        },
        body: JSON.stringify({
          invoiceId,
          transactionId: utrNumber.trim().toUpperCase(),
          amountDeclared: parsedAmount,
          receiptFileUrl: receiptUrl || undefined,
          idempotencyKey,
        }),
      });

      const data = await response.json();
      if (!data.success) {
        throw new Error(data.error || "Payment submission failed");
      }

      setSuccessInfo(
        data.isIdempotentReplay
          ? "Duplicate request caught! Your existing submission is already safely queued."
          : "Payment logged successfully! Student balance updates upon bursar bank audit."
      );

      setTimeout(() => {
        onSuccess(data.submissionId);
        onClose();
      }, 2000);
    } catch (err: any) {
      setIsSubmitting(false);
      setErrorMessage(err.message || "Failed to submit fee payment. Please retry.");
    }
  };

  return (
    <div className="fixed inset-0 z-50 flex items-center justify-center bg-black/40 backdrop-blur-sm p-4">
      <div className="w-full max-w-md bg-[#FAF7F2] border border-[#E5DFD7] rounded-xl shadow-xl overflow-hidden animate-in fade-in zoom-in-95 duration-150">
        {/* Header */}
        <div className="px-6 py-4 bg-[#F3EFE8] border-b border-[#E2D9CE] flex justify-between items-center">
          <div>
            <h3 className="text-sm font-bold text-[#682038]">Submit Fee Payment via UTR</h3>
            <p className="text-xs text-[#6E6862]">Invoice #{invoiceNumber} &bull; Total Due: ₹{totalDue.toLocaleString()}</p>
          </div>
          <button
            onClick={onClose}
            disabled={isSubmitting}
            className="text-[#9B948D] hover:text-[#242424] text-lg font-bold"
          >
            &times;
          </button>
        </div>

        {/* Form Body */}
        <form onSubmit={handleSubmit} className="p-6 space-y-4">
          <div>
            <label className="block text-xs font-semibold text-[#242424] mb-1">
              Bank Transaction ID / UTR Reference *
            </label>
            <input
              type="text"
              required
              disabled={isSubmitting}
              placeholder="e.g. 429384729104"
              value={utrNumber}
              onChange={(e) => setUtrNumber(e.target.value.toUpperCase())}
              className="w-full px-3 py-2 text-xs bg-white border border-[#DDD4C8] rounded-md font-mono focus:outline-none focus:border-[#682038]"
            />
            <p className="text-[11px] text-[#6E6862] mt-1">
              Unique reference generated by Google Pay, PhonePe, NEFT, or Net Banking.
            </p>
          </div>

          <div>
            <label className="block text-xs font-semibold text-[#242424] mb-1">
              Amount Paid (₹) *
            </label>
            <input
              type="number"
              required
              step="0.01"
              disabled={isSubmitting}
              value={amountDeclared}
              onChange={(e) => setAmountDeclared(e.target.value)}
              className="w-full px-3 py-2 text-xs bg-white border border-[#DDD4C8] rounded-md font-mono focus:outline-none focus:border-[#682038]"
            />
            <p className="text-[11px] text-[#6E6862] mt-1">
              Partial payments supported. Declared amount will be credited upon bursar verification.
            </p>
          </div>

          <div>
            <label className="block text-xs font-semibold text-[#242424] mb-1">
              Receipt File S3 URL (Optional)
            </label>
            <input
              type="url"
              disabled={isSubmitting}
              placeholder="https://..."
              value={receiptUrl}
              onChange={(e) => setReceiptUrl(e.target.value)}
              className="w-full px-3 py-2 text-xs bg-white border border-[#DDD4C8] rounded-md text-[#6E6862] focus:outline-none focus:border-[#682038]"
            />
          </div>

          {/* Idempotency Protection Badge */}
          <div className="p-3 bg-[#EFE9E1] rounded-md flex items-center justify-between text-[11px] text-[#6E6862]">
            <span>🛡️ Double-Tap Protected</span>
            <span className="font-mono text-[10px] text-[#9B948D] truncate max-w-[150px]">
              {idempotencyKey}
            </span>
          </div>

          {errorMessage && (
            <p className="text-xs text-[#BA1A1A] bg-[#FFEBEE] p-2.5 rounded-md border border-[#F8D7DA]">
              {errorMessage}
            </p>
          )}

          {successInfo && (
            <p className="text-xs text-[#2E7D32] bg-[#E8F5E9] p-2.5 rounded-md border border-[#D1E7DD]">
              {successInfo}
            </p>
          )}

          {/* Action buttons */}
          <div className="flex justify-end gap-3 pt-2">
            <button
              type="button"
              onClick={onClose}
              disabled={isSubmitting}
              className="px-4 py-2 text-xs font-semibold text-[#6E6862] hover:bg-[#ECE5DC] rounded-md"
            >
              Cancel
            </button>
            <button
              type="submit"
              disabled={isSubmitting}
              className={`px-5 py-2 text-xs font-semibold text-white rounded-md transition-all ${
                isSubmitting
                  ? "bg-[#9B948D] cursor-not-allowed"
                  : "bg-[#682038] hover:bg-[#54192D] active:scale-95"
              }`}
            >
              {isSubmitting ? "Submitting (Protected)..." : "Submit Payment for Audit"}
            </button>
          </div>
        </form>
      </div>
    </div>
  );
};
